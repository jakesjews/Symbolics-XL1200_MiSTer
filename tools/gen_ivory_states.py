#!/usr/bin/env python3
"""Generate rtl/ivory/ivory_cpu_state_enum.svh: every S_* state name used in the
Ivory processor sources, in order of first appearance."""
import re, sys, pathlib

rtl = pathlib.Path(__file__).resolve().parent.parent / "rtl" / "ivory"
names = []
for f in ["ivory_cpu_states.svh", "ivory_cpu_exec.svh", "ivory_cpu_insns.svh"]:
    for n in re.findall(r"\bS_[A-Z0-9_]+\b", (rtl / f).read_text()):
        if n not in names:
            names.append(n)
first = ["S_RESET", "S_HALT"]
names = first + [n for n in names if n not in first]
bits = max(1, (len(names) - 1).bit_length())
out = ["// Generated by tools/gen_ivory_states.py; do not edit.",
       f"  typedef enum logic [{bits - 1}:0] {{"]
for i in range(0, len(names), 6):
    out.append("    " + ", ".join(names[i:i + 6]) + ("," if i + 6 < len(names) else ""))
out.append("  } state_t;")
(rtl / "ivory_cpu_state_enum.svh").write_text("\n".join(out) + "\n")
print(f"{len(names)} states, {bits} bits")
