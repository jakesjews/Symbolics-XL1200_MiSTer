// Symbolics Ivory (I-machine) architectural definitions.
//
// A word is 40 bits: cdr<39:38> type<37:32> data<31:0>, held in a uint64_t.
#pragma once
#include <cstdint>

typedef uint64_t W;

enum Dtp {
  DTP_NULL = 000, DTP_MONITOR_FORWARD, DTP_HEADER_P, DTP_HEADER_I,
  DTP_EXTERNAL_VALUE_CELL_POINTER, DTP_ONE_Q_FORWARD, DTP_HEADER_FORWARD, DTP_ELEMENT_FORWARD,
  DTP_FIXNUM = 010, DTP_SMALL_RATIO, DTP_SINGLE_FLOAT, DTP_DOUBLE_FLOAT,
  DTP_BIGNUM, DTP_BIG_RATIO, DTP_COMPLEX, DTP_SPARE_NUMBER,
  DTP_INSTANCE = 020, DTP_LIST_INSTANCE, DTP_ARRAY_INSTANCE, DTP_STRING_INSTANCE,
  DTP_NIL = 024, DTP_LIST, DTP_ARRAY, DTP_STRING,
  DTP_SYMBOL = 030, DTP_LOCATIVE, DTP_LEXICAL_CLOSURE, DTP_DYNAMIC_CLOSURE,
  DTP_COMPILED_FUNCTION, DTP_GENERIC_FUNCTION, DTP_SPARE_POINTER_1, DTP_SPARE_POINTER_2,
  DTP_PHYSICAL_ADDRESS = 040, DTP_SPARE_IMMEDIATE_1, DTP_BOUND_LOCATION, DTP_CHARACTER,
  DTP_LOGIC_VARIABLE, DTP_GC_FORWARD, DTP_EVEN_PC, DTP_ODD_PC,
  DTP_CALL_COMPILED_EVEN = 050, DTP_CALL_COMPILED_ODD, DTP_CALL_INDIRECT, DTP_CALL_GENERIC,
  DTP_CALL_COMPILED_EVEN_PREFETCH, DTP_CALL_COMPILED_ODD_PREFETCH,
  DTP_CALL_INDIRECT_PREFETCH, DTP_CALL_GENERIC_PREFETCH,
  DTP_PACKED_INSTRUCTION_60 = 060,
};

enum Cdr { CDR_NEXT = 0, CDR_NIL = 1, CDR_NORMAL = 2, CDR_3 = 3 };

static inline uint32_t wdata(W w) { return (uint32_t)w; }
static inline int32_t wsdata(W w) { return (int32_t)(uint32_t)w; }
static inline int wtype(W w) { return (int)((w >> 32) & 077); }
static inline int wcdr(W w) { return (int)((w >> 38) & 3); }
static inline int wtag(W w) { return (int)((w >> 32) & 0377); }
static inline W mkw(int type, uint32_t d) { return ((W)(type & 077) << 32) | d; }
static inline W mkwc(int cdr, int type, uint32_t d) {
  return ((W)(cdr & 3) << 38) | ((W)(type & 077) << 32) | d;
}
static inline W mktag(int tag, uint32_t d) { return ((W)(tag & 0377) << 32) | d; }
static inline W setcdr(W w, int cdr) { return (w & 0x3FFFFFFFFFull) | ((W)(cdr & 3) << 38); }
static inline W stripcdr(W w) { return w & 0x3FFFFFFFFFull; }
static inline W settype(W w, int t) { return (w & ~(0x3Full << 32)) | ((W)(t & 077) << 32); }
static inline W setdata(W w, uint32_t d) { return (w & ~0xFFFFFFFFull) | d; }
static inline W fixnum(int32_t v) { return mkw(DTP_FIXNUM, (uint32_t)v); }
static inline bool is_fixnum(W w) { return wtype(w) == DTP_FIXNUM; }

// Data type classes (spec 1.1.4 / sysdef *POINTER-DATA-TYPES*).
static inline bool is_pointer_type(int t) {
  switch (t) {
  case DTP_NULL: case DTP_MONITOR_FORWARD: case DTP_HEADER_P:
  case DTP_EXTERNAL_VALUE_CELL_POINTER: case DTP_ONE_Q_FORWARD:
  case DTP_HEADER_FORWARD: case DTP_ELEMENT_FORWARD:
  case DTP_DOUBLE_FLOAT: case DTP_BIGNUM: case DTP_BIG_RATIO: case DTP_COMPLEX:
  case DTP_SPARE_NUMBER: case DTP_INSTANCE: case DTP_LIST_INSTANCE: case DTP_ARRAY_INSTANCE:
  case DTP_STRING_INSTANCE: case DTP_NIL: case DTP_LIST: case DTP_ARRAY: case DTP_STRING:
  case DTP_SYMBOL: case DTP_LOCATIVE: case DTP_LEXICAL_CLOSURE: case DTP_DYNAMIC_CLOSURE:
  case DTP_COMPILED_FUNCTION: case DTP_GENERIC_FUNCTION: case DTP_SPARE_POINTER_1:
  case DTP_SPARE_POINTER_2: case DTP_BOUND_LOCATION: case DTP_LOGIC_VARIABLE:
  case DTP_GC_FORWARD: case DTP_EVEN_PC: case DTP_ODD_PC:
    return true;
  default:
    return t >= DTP_CALL_COMPILED_EVEN && t <= DTP_CALL_GENERIC_PREFETCH;
  }
}

static inline bool is_numeric_type(int t) { return t >= DTP_FIXNUM && t <= DTP_SPARE_NUMBER; }

